#include <Arduino.h>
#include "auger.hpp"
#include "pump.hpp"
#include "config_store.hpp"
#include "clock.hpp"
#include "sensors.hpp"
#include "feeding_controller.hpp"
#include "ui.hpp"

void setup()
{
    // Outputs off first; NVS, I2C and the display initialize afterwards.
    Pump::begin();
    const bool motorReady = auger.begin();
    Serial.begin(115200);
    Config::begin();
    Sensors::begin();
    Clock::begin();
    FeedingController::begin();
    const bool uiReady = Ui::begin();
    Serial.printf("Cyber Bowl: motor timer=%s, UI buffer=%s, saved settings=%s\n",
                  motorReady ? "OK" : "ERROR", uiReady ? "OK" : "ERROR",
                  Config::loadedSavedSettings() ? "YES" : "DEFAULTS");
}

void loop()
{
    Ui::handleButtons();
    Sensors::update();
    Clock::update();
    FeedingController::update();
    FeedingController::updateSchedule(Ui::serviceMode());
    Ui::update();
    delay(1); // Yield to ESP32 system tasks; STEP is generated by the hardware timer.
}
