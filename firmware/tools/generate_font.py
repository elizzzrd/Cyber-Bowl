"""Optional: regenerate the built-in Russian font; not needed to build firmware."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math
root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf', 13)
codes = sorted(set(range(32, 127)) | set(range(0x410, 0x450)) | {0x401, 0x451})
bitmaps, glyphs = [], []
for code in codes:
    ch = chr(code)
    w = max(2, math.ceil(font.getlength(ch)))
    img = Image.new('L', (w, 16), 0)
    ImageDraw.Draw(img).text((0, -1), ch, font=font, fill=255)
    offset = len(bitmaps)
    for y in range(16):
        for byte in range((w + 7) // 8):
            bits = 0
            for b in range(8):
                x = byte * 8 + b
                if x < w and img.getpixel((x, y)) >= 100:
                    bits |= 1 << (7 - b)
            bitmaps.append(bits)
    glyphs.append((code, w, offset))
header = """// Generated by tools/generate_font.py. Do not edit by hand.
// Glyph bitmaps use DejaVu Sans. See docs/FONT-LICENSE.txt.
#pragma once
#include <cstdint>

namespace UiFontData {
struct Glyph { uint16_t code; uint8_t width; uint16_t offset; };
const uint8_t BITMAP_DATA[] = {
"""
header += '\n'.join(
    ','.join(str(value) for value in bitmaps[i:i + 32]) + ','
    for i in range(0, len(bitmaps), 32)
)
header += '\n};\nconst Glyph GLYPHS[] = {\n'
header += '\n'.join('{%d,%d,%d},' % item for item in glyphs)
header += '\n};\n}\n'

destination = root / 'src/generated/ui_font_data.hpp'
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text(header)
print(f'Generated {len(glyphs)} glyphs, {len(bitmaps)} bitmap bytes')
